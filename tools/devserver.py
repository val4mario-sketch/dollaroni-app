"""Local Dollaroni server (started by "Avvia Dollaroni.bat").

Serves the app files on http://127.0.0.1:<port>/ and in addition:
- accepts PUT to /out/... to save files generated by the tests to disk;
- sends the COOP/COEP headers, so the local AI can use all the processor cores;
- GET  /__dollaroni/info    installed version and GitHub repository to update from;
- POST /__dollaroni/update  downloads the latest version from GitHub and replaces the app files
                            (backup copy in out/backup-...; project files are not touched).
                            If the folder is a git clone it runs "git pull --ff-only".

Usage:  python tools/devserver.py [port] [--open] [--root=folder] [--no-isolation]
      --open also opens the browser (used by "Avvia Dollaroni.bat")
      --root serves another folder, e.g. the site prepared by tools/build_pwa.py
      --no-isolation does not send the COOP/COEP headers (the local AI will use one core)
"""
import datetime
import http.server
import io
import json
import pathlib
import shutil
import socket
import subprocess
import sys
import threading
import urllib.parse
import urllib.request
import webbrowser
import zipfile

APP = pathlib.Path(__file__).resolve().parent.parent
_root = next((a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith("--root=")), None)
ROOT = (APP / _root).resolve() if _root else APP
OUT = APP / "out"
ARGS = [a for a in sys.argv[1:] if not a.startswith("--")]
PORT = int(ARGS[0]) if ARGS else 8765
OPEN = "--open" in sys.argv
ISOLATION = "--no-isolation" not in sys.argv

# During an update these paths are never overwritten:
# generated files, team projects, the .bat (Windows rereads it while running) and the git folder.
KEEP = ("out/", ".git/", "_site/")
KEEP_SUFFIX = (".dollaroni.json",)
KEEP_FILES = ("Avvia Dollaroni.bat",)


def read_json(path, default=None):
    try:
        return json.loads(pathlib.Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return default


def git(*args, timeout=60):
    return subprocess.run(["git", "-C", str(APP), *args], capture_output=True, text=True, timeout=timeout)


def is_git_clone():
    return (APP / ".git").exists() and shutil.which("git") is not None


def update_config():
    return (read_json(APP / "dollaroni.config.json", {}) or {}).get("updates", {}) or {}


def repository():
    """owner/name of the repository: from dollaroni.config.json, otherwise from the git remote."""
    cfg = update_config()
    repo = (cfg.get("repository") or "").strip().strip("/")
    branch = (cfg.get("branch") or "main").strip()
    if not repo and is_git_clone():
        try:
            url = git("config", "--get", "remote.origin.url", timeout=10).stdout.strip()
            if "github.com" in url:
                repo = url.split("github.com", 1)[1].lstrip(":/").removesuffix(".git")
        except (OSError, subprocess.SubprocessError):
            pass
    return repo, branch


def info():
    v = read_json(APP / "version.json", {}) or {}
    repo, branch = repository()
    cfg = update_config()
    return {
        "app": "dollaroni", "version": v.get("version"), "date": v.get("date"),
        "repository": repo or None, "branch": branch,
        # optional, to update from an address other than GitHub
        "versionUrl": cfg.get("versionUrl") or None,
        "mode": "git" if is_git_clone() else "zip", "canUpdate": bool(repo or (cfg.get("versionUrl") and cfg.get("zipUrl"))),
    }


def update_from_github():
    """Brings the app to the latest version of the branch on GitHub. Returns a dict for the browser."""
    before = (read_json(APP / "version.json", {}) or {}).get("version")
    repo, branch = repository()
    zip_url = update_config().get("zipUrl")
    if not repo and not zip_url:
        return {"ok": False, "error": "GitHub repository not configured (dollaroni.config.json)."}

    if is_git_clone() and not zip_url:
        r = git("pull", "--ff-only", "origin", branch, timeout=120)
        if r.returncode != 0:
            return {"ok": False, "error": "git pull failed: " + (r.stderr or r.stdout).strip()[-400:]}
        after = (read_json(APP / "version.json", {}) or {}).get("version")
        changed = git("diff", "--name-only", "HEAD@{1}", "HEAD", timeout=30).stdout.split()
        return {"ok": True, "from": before, "to": after, "mode": "git", "written": len(changed),
                "restartNeeded": "tools/devserver.py" in changed}

    url = zip_url or f"https://codeload.github.com/{repo}/zip/refs/heads/{branch}"
    try:
        with urllib.request.urlopen(url, timeout=90) as resp:
            data = resp.read()
    except OSError as e:
        return {"ok": False, "error": f"Download from GitHub failed: {e}"}

    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    backup = OUT / f"backup-{before or 'vecchia'}-{stamp}"
    written = 0
    restart = False
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        names = [n for n in z.namelist() if not n.endswith("/")]
        prefix = names[0].split("/", 1)[0] + "/" if names else ""
        if not any(n == prefix + "version.json" for n in names):
            return {"ok": False, "error": "The downloaded zip does not look like Dollaroni (version.json is missing)."}
        for name in names:
            rel = name[len(prefix):]
            if not rel or rel.startswith(KEEP) or rel.endswith(KEEP_SUFFIX) or rel in KEEP_FILES:
                continue
            target = (APP / rel).resolve()
            if APP not in target.parents:
                continue  # odd path in the zip: ignored
            content = z.read(name)
            if target.exists():
                if target.read_bytes() == content:
                    continue
                dest = backup / rel
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(target, dest)
            target.parent.mkdir(parents=True, exist_ok=True)
            tmp = target.with_name(target.name + ".tmp-update")
            tmp.write_bytes(content)
            tmp.replace(target)
            written += 1
            restart = restart or rel == "tools/devserver.py"
    after = (read_json(APP / "version.json", {}) or {}).get("version")
    return {"ok": True, "from": before, "to": after, "mode": "zip", "written": written,
            "backup": str(backup.relative_to(APP)) if backup.exists() else None, "restartNeeded": restart}


class Handler(http.server.SimpleHTTPRequestHandler):
    # On Windows the registry may map .js to text/plain: ES modules would not start.
    extensions_map = {
        **http.server.SimpleHTTPRequestHandler.extensions_map,
        ".js": "text/javascript",
        ".mjs": "text/javascript",
        ".json": "application/json",
        ".webmanifest": "application/manifest+json",
        ".xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        ".docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
        ".wasm": "application/wasm",
        ".gguf": "application/octet-stream",
    }

    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(ROOT), **kwargs)

    def end_headers(self):
        self.send_header("Cache-Control", "no-store")
        # "Cross-origin isolation": lets the local AI use all the processor cores
        # (SharedArrayBuffer). The app loads no resources from other sites, so nothing breaks.
        if ISOLATION:
            self.send_header("Cross-Origin-Opener-Policy", "same-origin")
            self.send_header("Cross-Origin-Embedder-Policy", "require-corp")
        super().end_headers()

    def send_json(self, obj, status=200):
        body = json.dumps(obj).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def same_origin(self):
        # only the Dollaroni page can request the update: an external site cannot send
        # the custom header without a CORS preflight, which this server does not approve
        origin = self.headers.get("Origin", "")
        ok_origin = origin in (f"http://127.0.0.1:{PORT}", f"http://localhost:{PORT}")
        return ok_origin and self.headers.get("X-Dollaroni") == "update"

    def do_GET(self):
        if self.path.split("?", 1)[0] == "/__dollaroni/info":
            self.send_json(info())
            return
        super().do_GET()

    def do_POST(self):
        if self.path.split("?", 1)[0] != "/__dollaroni/update":
            self.send_error(404)
            return
        if not self.same_origin():
            self.send_error(403, "Request not allowed")
            return
        try:
            self.send_json(update_from_github())
        except Exception as e:  # noqa: BLE001 - the error is reported to the browser
            self.send_json({"ok": False, "error": f"Update failed: {e}"}, 500)

    def do_PUT(self):
        rel = urllib.parse.unquote(self.path.split("?", 1)[0]).lstrip("/")
        target = (APP / rel).resolve()
        if OUT.resolve() not in target.parents:
            self.send_error(403, "Writing is allowed only inside out/")
            return
        length = int(self.headers.get("Content-Length", 0))
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(self.rfile.read(length))
        self.send_response(201)
        self.end_headers()


class Server(http.server.ThreadingHTTPServer):
    # On Windows SO_REUSEADDR (on by default in http.server) lets two servers take
    # the same port: we turn it off and ask for exclusive use.
    allow_reuse_address = False

    def server_bind(self):
        if hasattr(socket, "SO_EXCLUSIVEADDRUSE"):
            self.socket.setsockopt(socket.SOL_SOCKET, socket.SO_EXCLUSIVEADDRUSE, 1)
        super().server_bind()


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    url = f"http://127.0.0.1:{PORT}/"
    try:
        httpd = Server(("127.0.0.1", PORT), Handler)
    except OSError:
        # port already in use: Dollaroni is probably already on, just open the browser
        print(f"Port {PORT} is already in use: opening {url}", flush=True)
        if OPEN:
            webbrowser.open(url)
        sys.exit(0)
    with httpd:
        v = info().get("version") or "?"
        print(f"Dollaroni {v}: {url}  (close this window to shut it down)", flush=True)
        if OPEN:
            threading.Timer(0.6, webbrowser.open, args=[url]).start()
        httpd.serve_forever()
