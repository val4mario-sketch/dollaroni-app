// New projects and elements with sensible starting values.


import { uid } from './format.js';
import { CURRENT_RULES, RULES_2026 } from '../engine/rules.js';

export const DEFAULT_SEASON = 2027;

export function emptyProject(season = DEFAULT_SEASON) {
  return {
    schema: 'dollaroni/1', name: 'New boat', team: 'SFT', season, stage: 'S1', concept: 'NEW', rules: CURRENT_RULES,
    catalogExtras: [], parts: [], lines: [],
  };
}

/**
 * New boat from the structure of the 2026 S1 estimate: same parts (with cost items
 * generated automatically) and same items not tied to the laminates (mould, consumables, rig…).
 */
export function projectFrom2026(s1) {
  const p = toRules2027(s1);
  Object.assign(p, { name: 'New boat', season: DEFAULT_SEASON, stage: 'S1', concept: 'NEW', description: 'Started from the structure of Meravijosa S1 2026: to be updated with the new project.' });
  delete p.savedAt;
  for (const part of p.parts) {
    part.autoLines = true;
    delete part.note;
  }
  // The fibre/resin/core rows are now generated by the parts; only any process remains.

  p.lines = p.lines.flatMap((l) => {
    if (!l.material?.check) return [l];
    if (!l.process) return [];
    const { material, ...rest } = l;
    return [{ ...rest, name: l.process.label || 'Process' }];
  });
  return p;
}

/**
 * Moves a project from the 2026 rules to 2027. Changes only what the new rulebook treats
 * differently: used parts lose the fixed cost of the old Table 3 and become priced items
 * (starting from the 2026 cost, to be confirmed on Agora: the source stays empty and the checks flag it).
 * The S1 baseline, if any, stays as it was: it is the submitted estimate.
 */
export function toRules2027(project) {
  const p = structuredClone(project);
  p.rules = '2027';
  for (const l of p.lines || []) {
    if (!l.usedPart) continue;
    const old = RULES_2026.usedParts[l.usedPart.element];
    const { participationYear, ...u } = l.usedPart;
    l.usedPart = { ...u, commercial: u.commercial ?? true };
    if (!l.material) l.material = { name: old?.en || l.name, unit: 'pc', qty: 1, price: old?.cost ?? null, priceSource: '' };
  }
  return p;
}

/**
 * S1 -> S2 transition. S1 as it is gets frozen and saved INSIDE the S2 project (baseline),
 * so the comparison required by section 2.3 of S2 is always available. S2 starts from the same parts
 * and items (same ids, so they can be compared one to one), all marked "estimated" until they are
 * updated with the real values.
 */
export function freezeToS2(project, now = new Date().toISOString()) {
  if (project.stage === 'S2') throw new Error('The project is already in S2');
  const frozen = structuredClone(project);
  delete frozen.baseline;
  delete frozen.savedAt;
  frozen.frozenAt = now;
  const s2 = structuredClone(frozen);
  delete s2.frozenAt;
  s2.stage = 'S2';
  s2.baseline = { stage: 'S1', frozenAt: now, project: frozen };
  for (const l of s2.lines) l.status = 'estimated';
  for (const p of s2.parts) p.status = 'estimated';
  return { s2, frozen };
}

export const DEFAULT_GROUPS = {
  hull: { limitGroup: 'hull', massGroup: 'hull' },
  foils: { limitGroup: null, massGroup: 'vertical_foils' }, // main/rudder, vertical/horizontal: chosen by the team (the limits change)

  mechanical_control: { limitGroup: 'other', massGroup: 'other' },
  gantry: { limitGroup: 'gantry', massGroup: 'other' },
  wingbars: { limitGroup: 'wingbars', massGroup: 'wings' },
  rig: { limitGroup: 'rig', massGroup: 'other' },
  electronics: { limitGroup: 'other', massGroup: 'other' },
};

export function newSubstack(prev) {
  if (prev) return { ...structuredClone(prev) };
  return {
    reinforcement: 'dry-fabric-basalt-fibers', matrix: 'std-epoxy/lamination-resin',
    plyArea: 1, plies: 2, arealWeight: 300, process: 'HAND LAYUP + VAC',
    reinforcementSource: 'new', matrixSource: 'new',
  };
}

export function newPart(component = 'hull') {
  return {
    id: uid('part'), name: 'New part', component, ...DEFAULT_GROUPS[component], autoLines: true,
    substacks: [newSubstack()],
  };
}

/** true if used parts have a fixed cost (2026 Table 3); in 2027 they are paid at the item price. */
export const fixedUsedParts = (rules) => Object.values(rules.usedParts || {}).some((d) => d.cost !== null);

/** Item types that can be added, with the hints of the rulebook in use. */
export function lineTypes(rules) {
  const fixed = fixedUsedParts(rules);
  const confirm = rules.sourcesToConfirm ? ' (to be confirmed on Agora)' : '';
  return [
    { id: 'material', label: 'Price list material', hint: 'moulds, gelcoat, adhesives, consumables, filaments…' },
    { id: 'process', label: 'Hourly process', hint: 'CNC, 3D printing, oven, autoclave…' },
    { id: 'hardware', label: 'Hardware / priced item', hint: fixed ? 'blocks, ropes, electronics (MSRP price)' : 'blocks, ropes, electronics (price from Agora or MSRP, with the source)' },
    fixed
      ? { id: 'used', label: 'Used part (Table 3)', hint: 'used foils or rig: fixed cost and handicap' }
      : { id: 'used', label: 'Used or commercial part', hint: 'foils, sails, masts…: price from Agora; −100 points if commercial from 2017 (§11.1.5)' },
    { id: 'upcycled', label: 'Upcycled element', hint: `from obsolete artefacts: 0 SM$${confirm}, the origin must be stated` },
  ];
}

export function newLine(type, component, rules = RULES_2026) {
  const base = { id: uid('line'), component, name: '' };
  switch (type) {
    case 'material': return { ...base, name: 'New item', material: { ref: 'mdf-hdf-wood', qty: 0, source: 'new' } };
    case 'process': return { ...base, name: 'Process', process: { ref: 'machining', hours: 0 } };
    case 'hardware': return { ...base, name: 'Hardware', material: { name: '', unit: 'pc', qty: 1, price: 0, priceSource: '' } };
    case 'used':
      if (fixedUsedParts(rules)) return { ...base, name: 'Used part', usedPart: { element: 'main_vertical', year: 2014 }, origin: '' };
      // 2027: price to enter (no fixed cost); year to state for §11.1.5

      return { ...base, name: 'Used part', material: { name: rules.usedParts.main_vertical.en, unit: 'pc', qty: 1, priceSource: '' }, usedPart: { element: 'main_vertical', year: null, commercial: true }, origin: '' };
    case 'upcycled': return { ...base, name: 'Upcycled element', material: { name: '', unit: 'pc', qty: 1, source: 'upcycled' }, origin: '' };
    default: throw new Error('Unknown item type: ' + type);
  }
}

export function lineType(l) {
  if (l.usedPart) return 'used';
  if (!l.material && l.process) return 'process';
  if (l.material && !l.material.ref) return l.material.source === 'upcycled' ? 'upcycled' : 'hardware';
  return 'material';
}
